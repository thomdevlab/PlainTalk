# ULTIMATE TALK2EXE ENGINE
# ============================================================================

class UltimateTalk2Exe:
    """Ultimate direct .talk to .exe converter"""
    
    def __init__(self):
        self.python_exe = sys.executable
        self.build_log = []
    
    def _log(self, message: str):
        """Add message to build log"""
        timestamp = time.strftime("%H:%M:%S")
        log_entry = f"[{timestamp}] {message}"
        self.build_log.append(log_entry)
        print(log_entry)
    
    def _transpile_talk_to_python(self, talk_file: str) -> str:
        """Transpile PlainTalk to Python using existing transpiler"""
        self._log(f"Transpiling {talk_file}")
        
        try:
            # Import PlainTalk transpiler
            sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
            import plaintalk
            
            # Transpile the file
            with open(talk_file, 'r', encoding='utf-8') as f:
                talk_source = f.read()
            
            python_code = plaintalk.transpile_lines(talk_source.split('\n'))
            
            # Add TE tribute to generated Python code
            te_comment = "\n# TE Tribute - Generated by Talk2Exe with TE's legacy in mind\n# Dedicated to TE, creator of PlainTalk\n"
            python_code = te_comment + python_code
            
            self._log(f"Transpilation complete with TE tribute")
            return python_code
            
        except Exception as e:
            raise RuntimeError(f"Failed to transpile {talk_file}: {e}")
    
    def _create_python_script(self, python_code: str, output_dir: str) -> str:
        """Create the Python script file"""
        script_path = os.path.join(output_dir, "program.py")
        
        with open(script_path, 'w', encoding='utf-8') as f:
            f.write(python_code)
        
        self._log(f"Created Python script: {script_path}")
        return script_path
    
    def _create_simple_launcher(self, python_script: str, output_exe: str, 
                              console_mode: bool = True) -> str:
        """Create simple launcher script"""
        launcher_code = f'''@echo off
cd /d "%~dp0"
set PYTHONPATH=%~dp0
echo Running PlainTalk program...
echo TE Tribute - Dedicated to TE, creator of PlainTalk
echo.
{self.python_exe} program.py
if {"true" if console_mode else "false"} pause
'''
        
        launcher_path = os.path.join(os.path.dirname(output_exe), "run_program.bat")
        
        with open(launcher_path, 'w') as f:
            f.write(launcher_code)
        
        self._log(f"Created launcher: {launcher_path}")
        return launcher_path
    
    def convert_to_exe(self, input_path: str, output_path: str,
                     console_mode: bool = True,
                     progress_callback=None) -> bool:
        """Main conversion method - DIRECT .talk to .exe"""
        try:
            if progress_callback:
                progress_callback("Reading PlainTalk file...")
            
            # Step 1: Transpile .talk to Python
            python_code = self._transpile_talk_to_python(input_path)
            
            if progress_callback:
                progress_callback("Creating Python script...")
            
            # Step 2: Create temporary directory
            temp_dir = tempfile.mkdtemp(prefix="talk2exe_ultimate_")
            self._log(f"Created temporary directory: {temp_dir}")
            
            try:
                # Step 3: Create Python script
                python_script = self._create_python_script(python_code, temp_dir)
                
                if progress_callback:
                    progress_callback("Creating executable launcher...")
                
                # Step 4: Create launcher
                launcher_path = self._create_simple_launcher(
                    python_script, output_path, console_mode
                )
                
                # Step 5: Copy Python script to output directory
                output_dir = os.path.dirname(output_path)
                final_script_path = os.path.join(output_dir, "program.py")
                
                if os.path.exists(final_script_path):
                    os.remove(final_script_path)
                
                shutil.copy2(python_script, final_script_path)
                self._log(f"Copied Python script to: {final_script_path}")
                
                if progress_callback:
                    progress_callback("Build completed successfully!")
                
                return True
                
            except Exception as e:
                self._log(f"Build error: {e}")
                return False
            finally:
                # Clean up temporary directory
                if os.path.exists(temp_dir):
                    shutil.rmtree(temp_dir)
                    self._log(f"Cleaned up temporary directory: {temp_dir}")
                
        except Exception as e:
            if progress_callback:
                progress_callback(f"Error: {e}")
            return False

