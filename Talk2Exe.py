class UltimateTalk2ExeGUI:
    """GUI for Ultimate Talk2Exe"""
    
    def __init__(self):
        self.app = UltimateTalk2Exe()
        self.root = tk.Tk()
        self.setup_ui()
    
    def setup_ui(self):
        """Setup main GUI"""
        self.root.title("Talk2Exe ULTIMATE - Direct .talk to .exe")
        self.root.geometry("700x500")
        self.root.resizable(True, True)
        
        # Create main frame
        main_frame = ttk.Frame(self.root, padding="10")
        main_frame.grid(row=0, column=0, sticky=(tk.W, tk.E, tk.N, tk.S))
        
        # Input file selection
        ttk.Label(main_frame, text="PlainTalk File (.talk):").grid(row=0, column=0, sticky=tk.W, pady=5)
        
        input_frame = ttk.Frame(main_frame)
        input_frame.grid(row=1, column=0, columnspan=2, sticky=(tk.W, tk.E), pady=5)
        
        self.input_var = tk.StringVar()
        self.input_entry = ttk.Entry(input_frame, textvariable=self.input_var, width=50)
        self.input_entry.pack(side=tk.LEFT, fill=tk.X, expand=True, padx=(0, 5))
        
        ttk.Button(input_frame, text="Browse...", command=self.browse_input_file).pack(side=tk.LEFT)
        
        # Output file selection
        ttk.Label(main_frame, text="Output Executable (.exe):").grid(row=2, column=0, sticky=tk.W, pady=5)
        
        output_frame = ttk.Frame(main_frame)
        output_frame.grid(row=3, column=0, columnspan=2, sticky=(tk.W, tk.E), pady=5)
        
        self.output_var = tk.StringVar()
        self.output_entry = ttk.Entry(output_frame, textvariable=self.output_var, width=50)
        self.output_entry.pack(side=tk.LEFT, fill=tk.X, expand=True, padx=(0, 5))
        
        ttk.Button(output_frame, text="Browse...", command=self.browse_output_file).pack(side=tk.LEFT)
        
        # Build options
        options_frame = ttk.LabelFrame(main_frame, text="Build Options", padding="10")
        options_frame.grid(row=4, column=0, columnspan=2, sticky=(tk.W, tk.E), pady=10)
        
        # Console mode
        self.console_var = tk.BooleanVar(value=True)
        ttk.Checkbutton(options_frame, text="Console Application", 
                    variable=self.console_var).grid(row=0, column=0, sticky=tk.W)
        
        ttk.Label(options_frame, text="Note: Creates .exe + .bat launcher using system Python").grid(row=1, column=0, sticky=tk.W, pady=5)
        
        # Build button
        self.build_button = ttk.Button(main_frame, text="Build Executable", 
                                   command=self.build_executable)
        self.build_button.grid(row=5, column=0, pady=10)
        
        # Progress
        self.progress_var = tk.StringVar(value="Ready (Ultimate Version)")
        ttk.Label(main_frame, textvariable=self.progress_var).grid(row=6, column=0, pady=5)
        
        # Log area
        log_frame = ttk.LabelFrame(main_frame, text="Build Log", padding="5")
        log_frame.grid(row=7, column=0, columnspan=2, sticky=(tk.W, tk.E, tk.N, tk.S), pady=10)
        
        self.log_text = scrolledtext.ScrolledText(log_frame, height=8, width=70)
        self.log_text.pack(fill=tk.BOTH, expand=True)
        
        # Configure grid weights
        main_frame.columnconfigure(0, weight=1)
        self.root.columnconfigure(0, weight=1)
        self.root.rowconfigure(0, weight=1)
    
    def browse_input_file(self):
        """Browse for .talk file"""
        filename = filedialog.askopenfilename(
            title="Select PlainTalk File",
            filetypes=[("PlainTalk files", "*.talk"), ("All files", "*.*")]
        )
        if filename:
            self.input_var.set(filename)
            # Auto-generate output name
            if not self.output_var.get():
                output_name = Path(filename).stem + ".exe"
                self.output_var.set(str(Path(filename).parent / output_name))
    
    def browse_output_file(self):
        """Browse for output file"""
        filename = filedialog.asksaveasfilename(
            title="Save Executable As",
            defaultextension=".exe",
            filetypes=[("Executable files", "*.exe"), ("All files", "*.*")]
        )
        if filename:
            self.output_var.set(filename)
    
    def update_progress(self, message: str):
        """Update progress display"""
        self.progress_var.set(message)
        self.root.update_idletasks()
    
    def add_log_message(self, message: str):
        """Add message to log area"""
        self.log_text.insert(tk.END, message + "\n")
        self.log_text.see(tk.END)
        self.root.update_idletasks()
    
    def build_executable(self):
        """Build executable in separate thread"""
        input_path = self.input_var.get()
        output_path = self.output_var.get()
        
        if not input_path:
            messagebox.showerror("Error", "Please select a PlainTalk file")
            return
        
        if not output_path:
            messagebox.showerror("Error", "Please specify an output file")
            return
        
        if not input_path.lower().endswith('.talk'):
            messagebox.showerror("Error", "Input file must be a .talk file")
            return
        
        if not os.path.exists(input_path):
            messagebox.showerror("Error", f"Input file not found: {input_path}")
            return
        
        # Disable build button during build
        self.build_button.config(state='disabled')
        
        # Start build in separate thread
        def build_thread():
            success = self.app.convert_to_exe(
                input_path, output_path,
                console_mode=self.console_var.get(),
                progress_callback=self.update_progress
            )
            
            # Update UI from main thread
            self.root.after(0, self.build_complete, success)
        
        thread = threading.Thread(target=build_thread)
        thread.daemon = True
        thread.start()
    
    def build_complete(self, success: bool):
        """Handle build completion"""
        self.build_button.config(state='normal')
        
        if success:
            self.update_progress("Build completed successfully!")
            messagebox.showinfo("Success", "Executable built successfully!")
        else:
            self.update_progress("Build failed!")
            messagebox.showerror("Error", "Build failed. Check the log for details.")
        
        # Add build log to display
        for message in self.app.build_log:
            self.add_log_message(message)
    
    def run(self):
        """Start the GUI"""
        self.root.mainloop()

