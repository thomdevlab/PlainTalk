class UltimateTalk2ExeCLI:
    """CLI for Ultimate Talk2Exe"""
    
    def __init__(self):
        self.app = UltimateTalk2Exe()
    
    def run(self, args: List[str]) -> int:
        """Run CLI with given arguments"""
        parser = argparse.ArgumentParser(
            description="Talk2Exe ULTIMATE - Direct .talk to .exe without bytecode",
            formatter_class=argparse.RawDescriptionHelpFormatter,
            epilog="""
Examples:
  %(prog)s program.talk program.exe                    # Basic conversion
  %(prog)s program.talk program.exe --windowed          # Windowed application
            """
        )
        
        parser.add_argument('input', help='Input .talk file')
        parser.add_argument('output', help='Output .exe file')
        
        parser.add_argument('--console', action='store_true', default=True,
                        help='Build as console application (default)')
        parser.add_argument('--windowed', action='store_true',
                        help='Build as windowed application')
        parser.add_argument('--verbose', '-v', action='store_true',
                        help='Show detailed build output')
        
        parsed_args = parser.parse_args(args)
        
        # Validate arguments
        if not os.path.exists(parsed_args.input):
            print(f"Error: Input file not found: {parsed_args.input}", file=sys.stderr)
            return 1
        
        if not parsed_args.input.lower().endswith('.talk'):
            print(f"Error: Input file must be a .talk file", file=sys.stderr)
            return 1
        
        # Handle conflicting options
        if parsed_args.windowed and parsed_args.console:
            print("Error: Cannot specify both --console and --windowed", file=sys.stderr)
            return 1
        
        # Set build options
        console_mode = parsed_args.console and not parsed_args.windowed
        
        # Show build info
        print(f"Talk2Exe ULTIMATE")
        print(f"Input: {parsed_args.input}")
        print(f"Output: {parsed_args.output}")
        print(f"Mode: {'Console' if console_mode else 'Windowed'}")
        print(f"Method: Direct .talk to Python to .exe (NO BYTECODE)")
        print()
        
        # Progress callback for CLI
        def cli_progress(message: str):
            if parsed_args.verbose:
                print(f"[INFO] {message}")
            else:
                print(message)
        
        # Convert with progress reporting
        success = self.app.convert_to_exe(
            parsed_args.input, parsed_args.output,
            console_mode=console_mode,
            progress_callback=cli_progress
        )
        
        if success:
            print("\n✅ Build completed successfully!")
            print("Files created:")
            print(f"  {parsed_args.output} (main executable)")
            print(f"  {os.path.dirname(parsed_args.output)}/run_program.bat (launcher)")
            print(f"  {os.path.dirname(parsed_args.output)}/program.py (Python script)")
            return 0
        else:
            print("\n❌ Build failed!")
            if parsed_args.verbose:
                print("\nBuild log:")
                for message in self.app.build_log:
                    print(f"  {message}")
            return 1

# ============================================================================
# MAIN ENTRY POINT
# ============================================================================

def main():
    """Main entry point"""
    # Check if running in CLI mode
    if len(sys.argv) > 1:
        # CLI mode
        cli = UltimateTalk2ExeCLI()
        return cli.run(sys.argv[1:])
    else:
        # GUI mode
        try:
            gui = UltimateTalk2ExeGUI()
            gui.run()
        except KeyboardInterrupt:
            print("\nApplication interrupted by user")
            return 1
        except Exception as e:
            print(f"GUI error: {e}", file=sys.stderr)
            return 1
    
    return 0

if __name__ == "__main__":
    sys.exit(main())
